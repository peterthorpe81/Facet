using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Facet.Generators;

/// <summary>Emits strongly typed option builders and query extensions for nested facet projections.</summary>
internal static class ProjectionOptionsGenerator
{
    public static string Generate(
        FacetTargetModel model,
        Dictionary<string, List<FacetTargetModel>> facetLookup,
        bool includeEfCoreExtensions)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        if (!string.IsNullOrWhiteSpace(model.Namespace))
            sb.AppendLine($"namespace {model.Namespace};");
        sb.AppendLine();

        var uniqueName = model.ContainingTypes.Length == 0 ? model.Name : MakeIdentifier(model.FullName);
        var optionsName = uniqueName + "ProjectionOptions";
        var nestedMembers = model.Members.Where(IsNestedNavigation).ToArray();
        EmitOptionsClass(sb, optionsName, nestedMembers, facetLookup, "", new HashSet<string> { model.FullName }, 0);

        var qualifiedModelName = model.Namespace != null && !model.FullName.StartsWith(model.Namespace + ".", StringComparison.Ordinal)
            ? model.Namespace + "." + model.FullName
            : model.FullName;
        var targetType = "global::" + qualifiedModelName;
        var extensionsName = uniqueName + "ProjectionExtensions";
        sb.AppendLine($"public static class {extensionsName}");
        sb.AppendLine("{");
        sb.AppendLine($"    public static global::System.Linq.IQueryable<TTarget> SelectFacet<TTarget>(this global::System.Linq.IQueryable source, global::System.Action<{optionsName}> configure)");
        sb.AppendLine("        where TTarget : class");
        sb.AppendLine("    {");
        sb.AppendLine("        if (source is null) throw new global::System.ArgumentNullException(nameof(source));");
        sb.AppendLine("        if (configure is null) throw new global::System.ArgumentNullException(nameof(configure));");
        sb.AppendLine($"        if (typeof(TTarget) != typeof({targetType})) throw new global::System.InvalidOperationException($\"Options are for {model.Name}; requested target was {{typeof(TTarget).Name}}.\");");
        sb.AppendLine($"        var options = new {optionsName}();");
        sb.AppendLine("        configure(options);");
        sb.AppendLine($"        var projection = global::Facet.Extensions.FacetProjectionOptions.Apply({targetType}.Projection, options);");
        sb.AppendLine("        return global::Facet.Extensions.FacetExtensions.SelectFacet<TTarget>(source, projection);");
        sb.AppendLine("    }");

        if (includeEfCoreExtensions)
        {
            sb.AppendLine();
            sb.AppendLine($"    public static async global::System.Threading.Tasks.Task<global::System.Collections.Generic.List<TTarget>> ToFacetsAsync<TTarget>(this global::System.Linq.IQueryable source, global::System.Action<{optionsName}> configure, global::System.Threading.CancellationToken cancellationToken = default)");
            sb.AppendLine("        where TTarget : class");
            sb.AppendLine("    {");
            sb.AppendLine($"        var projected = SelectFacet<TTarget>(source, configure);");
            sb.AppendLine("        return await global::Microsoft.EntityFrameworkCore.EntityFrameworkQueryableExtensions.ToListAsync(projected, cancellationToken).ConfigureAwait(false);");
            sb.AppendLine("    }");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitOptionsClass(
        StringBuilder sb,
        string className,
        IReadOnlyList<FacetMember> members,
        Dictionary<string, List<FacetTargetModel>> facetLookup,
        string indent,
        HashSet<string> visitedModels,
        int depth)
    {
        sb.AppendLine($"{indent}public sealed class {className} : global::Facet.Extensions.FacetProjectionOptions");
        sb.AppendLine($"{indent}{{");

        foreach (var member in members)
        {
            var childType = member.IsCollection
                ? ExpressionBuilder.ExtractElementTypeFromCollectionTypeName(member.TypeName).TrimEnd('?')
                : member.TypeName.TrimEnd('?');
            var childModel = FindModel(childType, facetLookup, member.NestedFacetSourceTypeName);
            if (childModel == null) continue;

            var sourceType = member.NestedFacetSourceTypeName ?? childModel.SourceTypeName;
            if (member.IsCollection)
            {
                sourceType = member.NestedFacetSourceTypeName ??
                    (member.SourceMemberTypeName != null
                        ? ExpressionBuilder.ExtractElementTypeFromCollectionTypeName(member.SourceMemberTypeName)
                        : childModel.SourceTypeName);
                sb.AppendLine($"{indent}    public void Include{member.Name}(global::System.Linq.Expressions.Expression<global::System.Func<{sourceType}, bool>>? where = null)");
                sb.AppendLine($"{indent}        => Include(\"{member.Name}\", where);");
            }
            else
            {
                sb.AppendLine($"{indent}    public void Include{member.Name}() => Include(\"{member.Name}\");");
            }

            var childOptionsType = GetChildOptionsType(member, depth);
            sb.AppendLine($"{indent}    public {childOptionsType} {member.Name}Options");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        get");
            sb.AppendLine($"{indent}        {{");
            sb.AppendLine($"{indent}            Include(\"{member.Name}\");");
            sb.AppendLine($"{indent}            return ({childOptionsType})GetChild(\"{member.Name}\")!;");
            sb.AppendLine($"{indent}        }}");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine();
        }

        sb.AppendLine($"{indent}    public {className}()");
        sb.AppendLine($"{indent}    {{");
        foreach (var member in members)
        {
            if (!IsNestedNavigation(member)) continue;
            var childType = member.IsCollection
                ? ExpressionBuilder.ExtractElementTypeFromCollectionTypeName(member.TypeName).TrimEnd('?')
                : member.TypeName.TrimEnd('?');
            var childModel = FindModel(childType, facetLookup, member.NestedFacetSourceTypeName);
            if (childModel != null)
                sb.AppendLine($"{indent}        RegisterChild(\"{member.Name}\", new {GetChildOptionsType(member, depth)}());");
        }
        sb.AppendLine($"{indent}    }}");

        foreach (var member in members)
        {
            if (!IsNestedNavigation(member)) continue;
            var childType = member.IsCollection
                ? ExpressionBuilder.ExtractElementTypeFromCollectionTypeName(member.TypeName).TrimEnd('?')
                : member.TypeName.TrimEnd('?');
            var childModel = FindModel(childType, facetLookup, member.NestedFacetSourceTypeName);
            if (childModel == null) continue;

            sb.AppendLine();
            var childMembers = visitedModels.Contains(childModel.FullName)
                ? Array.Empty<FacetMember>()
                : childModel.Members.Where(IsNestedNavigation).ToArray();
            var childVisitedModels = new HashSet<string>(visitedModels) { childModel.FullName };
            EmitOptionsClass(sb, GetChildOptionsType(member, depth), childMembers, facetLookup, indent + "    ", childVisitedModels, depth + 1);
        }

        sb.AppendLine($"{indent}}}");
    }

    private static bool IsNestedNavigation(FacetMember member) =>
        member.IsNestedFacet && member.MapFromIncludeInProjection;

    private static string GetChildOptionsType(FacetMember member, int depth) =>
        member.Name + "OptionsBuilder" + (depth + 1).ToString(System.Globalization.CultureInfo.InvariantCulture);

    private static string MakeIdentifier(string name)
    {
        var chars = name.Select(character => char.IsLetterOrDigit(character) || character == '_' ? character : '_').ToArray();
        return new string(chars);
    }

    private static FacetTargetModel? FindModel(
        string typeName,
        Dictionary<string, List<FacetTargetModel>> facetLookup,
        string? preferredSourceTypeName)
    {
        var simpleName = typeName.Replace("global::", "").Split('.', ':').Last();
        foreach (var models in facetLookup.Values)
        {
            foreach (var model in models)
            {
                if (model.Name == simpleName || model.FullName == typeName || model.FullName.EndsWith("." + simpleName, StringComparison.Ordinal))
                {
                    if (preferredSourceTypeName == null || model.SourceTypeName == preferredSourceTypeName)
                        return model;
                }
            }
        }
        return facetLookup.Values.SelectMany(models => models).FirstOrDefault(model => model.Name == simpleName);
    }
}
